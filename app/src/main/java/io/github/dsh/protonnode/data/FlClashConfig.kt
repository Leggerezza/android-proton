package io.github.dsh.protonnode.data

/**
 * Generates the mihomo (FlClash) configuration this node expects, and checks
 * that a config actually protects against the loop described in PROMPT.md 5.6:
 * FlClash must send the node's own traffic DIRECT, otherwise the tunnel is
 * carried inside the tunnel it feeds.
 *
 * The YAML is intentionally small and readable: FlClash users import it as a
 * profile.
 */
object FlClashConfig {
    /** GameNative's package; used for the GAME group rule. */
    const val GAME_PACKAGE = "app.gamenative"

    fun generate(
        selfPackage: String,
        gamePackage: String = GAME_PACKAGE,
        socksPort: Int = 1080,
    ): String =
        """
# Proton node -> mihomo profile (generated by Proton Node)
# 1. Import this file in FlClash as a profile.
# 2. Enable TUN mode, "rule" proxy mode, and include GameNative / exclude this app.
mixed-port: 7890
allow-lan: false
mode: rule
log-level: info
ipv6: false
unified-delay: true
tcp-concurrent: true
# PROCESS-NAME rules need /proc scanning; "strict" is what makes them reliable.
find-process-mode: strict
profile:
  store-selected: true

dns:
  enable: true
  enhanced-mode: fake-ip
  fake-ip-range: 198.18.0.1/16
  fake-ip-filter:
    - '*.lan'
    - '*.local'
    # The node talks to the Proton API directly; a fake-ip (198.18.x) there
    # would break that dial (same insight as the Windows profile).
    - '+.proton.me'
    - '+.protonmail.ch'
    - '+.protonvpn.com'
  nameserver:
    - 223.5.5.5
    - 119.29.29.29
  proxy-server-nameserver:
    - 223.5.5.5

tun:
  enable: true
  stack: mixed
  # mihomo's usual default. A small TUN MTU starves the outer TLS connection
  # that carries WireGuard, which shows up as SOCKS dials failing (rep 0x4).
  mtu: 9000
  auto-route: true

proxies:
  - name: proton-node
    type: socks5
    server: 127.0.0.1
    port: $socksPort
    udp: true

proxy-groups:
  - name: PROXY
    type: select
    proxies:
      - proton-node
      - DIRECT
  - name: GAME
    type: select
    proxies:
      - proton-node
      - DIRECT

rules:
  # Loop guard (PROMPT.md 5.6): this app must never be proxied.
  - PROCESS-NAME,$selfPackage,DIRECT
  # Game traffic goes through the node; the order keeps it above the CN rules.
  - PROCESS-NAME,$gamePackage,GAME
  # Domains that polluted DNS often resolves to a mainland IP
  # (safebrowsing.googleapis.com -> 120.253.x). Domain rules must sit above
  # GEOSITE/GEOIP or those connections would be sent DIRECT and fail.
  - DOMAIN-SUFFIX,googleapis.com,PROXY
  - DOMAIN-SUFFIX,google.com,PROXY
  - DOMAIN-SUFFIX,gstatic.com,PROXY
  - DOMAIN-SUFFIX,googleusercontent.com,PROXY
  - DOMAIN-SUFFIX,googlevideo.com,PROXY
  - DOMAIN-SUFFIX,ggpht.com,PROXY
  - DOMAIN-SUFFIX,ytimg.com,PROXY
  - DOMAIN-SUFFIX,youtube.com,PROXY
  - DOMAIN-SUFFIX,gmail.com,PROXY
  - DOMAIN-SUFFIX,github.com,PROXY
  - DOMAIN-SUFFIX,githubusercontent.com,PROXY
  - DOMAIN-SUFFIX,openai.com,PROXY
  - DOMAIN-SUFFIX,chatgpt.com,PROXY
  - DOMAIN-SUFFIX,oaistatic.com,PROXY
  - DOMAIN-SUFFIX,oaiusercontent.com,PROXY
  - DOMAIN-SUFFIX,anthropic.com,PROXY
  - DOMAIN-SUFFIX,claude.ai,PROXY
  - DOMAIN-SUFFIX,x.com,PROXY
  - DOMAIN-SUFFIX,twitter.com,PROXY
  - DOMAIN-SUFFIX,telegram.org,PROXY
  - DOMAIN-SUFFIX,t.me,PROXY
  - DOMAIN-SUFFIX,wikipedia.org,PROXY
  - DOMAIN-SUFFIX,discord.com,PROXY
  - DOMAIN-SUFFIX,reddit.com,PROXY
  - DOMAIN-SUFFIX,cloudflare-dns.com,PROXY
  - DOMAIN-SUFFIX,dns.google,PROXY
  # Domestic traffic must stay domestic: WeChat/Alipay/Taobao over a foreign exit
  # is slow and trips their risk control (foreign login warnings).
  - DOMAIN-SUFFIX,weixin.qq.com,DIRECT
  - DOMAIN-SUFFIX,wechat.com,DIRECT
  - DOMAIN-SUFFIX,qq.com,DIRECT
  - DOMAIN-SUFFIX,tencent.com,DIRECT
  - DOMAIN-SUFFIX,alipay.com,DIRECT
  - DOMAIN-SUFFIX,taobao.com,DIRECT
  - DOMAIN-SUFFIX,tmall.com,DIRECT
  - DOMAIN-SUFFIX,jd.com,DIRECT
  - DOMAIN-SUFFIX,baidu.com,DIRECT
  - DOMAIN-SUFFIX,bilibili.com,DIRECT
  - DOMAIN-SUFFIX,douyin.com,DIRECT
  - DOMAIN-SUFFIX,meituan.com,DIRECT
  - DOMAIN-SUFFIX,163.com,DIRECT
  - GEOSITE,cn,DIRECT
  # Literal-IP only: with fake-ip a domain must be judged by GEOSITE above.
  - GEOIP,CN,DIRECT,no-resolve
  - IP-CIDR,10.0.0.0/8,DIRECT,no-resolve
  - IP-CIDR,172.16.0.0/12,DIRECT,no-resolve
  - IP-CIDR,192.168.0.0/16,DIRECT,no-resolve
  - IP-CIDR,127.0.0.0/8,DIRECT,no-resolve
  - MATCH,PROXY
""".trimStart()

    /**
     * Returns a list of human-readable problems, empty when the config is safe.
     * Deliberately textual: no YAML parser on the device, only the invariants we
     * really rely on.
     */
    fun validate(
        text: String,
        selfPackage: String,
    ): List<String> {
        val problems = mutableListOf<String>()
        if (text.isBlank()) {
            problems += "config is empty"
            return problems
        }
        val rulesSection = text.substringAfter("\nrules:", text.substringAfter("rules:", ""))
        val rules =
            rulesSection
                .lineSequence()
                .map { it.trim() }
                .filter { it.startsWith("- ") && it.contains(",") }
                .map { it.removePrefix("- ").trim() }
                .toList()
        if (rules.isEmpty()) {
            problems += "no rules found"
            return problems
        }
        val selfRule = "PROCESS-NAME," + selfPackage + ",DIRECT"
        val selfIndex = rules.indexOfFirst { it == selfRule }
        if (selfIndex < 0) {
            problems += "missing loop guard rule: " + selfRule
        } else if (selfIndex > 0 && rules.take(selfIndex).any { it.contains(selfPackage) }) {
            problems += "the loop guard must be the first rule that mentions " + selfPackage
        }
        if (!rules.any { it.startsWith("MATCH,") }) {
            problems += "no MATCH rule"
        }
        // Domestic apps must not be dragged through a foreign exit.
        if (!text.contains("+.protonmail.ch") || !text.contains("fake-ip-filter")) {
            problems += "the Proton API domains must be excluded from fake-ip, or the API dial breaks"
        }
        if (text.contains("GEOIP,CN,DIRECT\n")) {
            problems += "GEOIP,CN must use no-resolve (fake-ip sends domains to the wrong side)"
        }
        val cnRule = rules.indexOfFirst { it == "GEOSITE,cn,DIRECT" || it == "GEOIP,CN,DIRECT,no-resolve" }
        if (cnRule < 0) {
            problems += "no CN direct rule (GEOSITE,cn / GEOIP,CN): WeChat and other domestic apps would be proxied"
        } else {
            val match = rules.indexOfFirst { it.startsWith("MATCH,") }
            if (match in 0..<cnRule) problems += "the CN direct rule must come before MATCH"
        }
        if (rules.any { it.startsWith("MATCH,") } && rules.indexOfFirst { it.startsWith("MATCH,") } < selfIndex) {
            problems += "MATCH must come after the loop guard"
        }
        val socks = Regex("""type:\s*socks5[\s\S]*?port:\s*(\d+)[\s\S]*?udp:\s*(true|false)""").find(text)
        if (socks == null) {
            problems += "no socks5 proxy block"
        } else {
            if (socks.groupValues[1] != "1080") problems += "socks5 port is " + socks.groupValues[1] + ", expected 1080"
            if (socks.groupValues[2] != "true") problems += "socks5 udp must be true"
        }
        return problems
    }
}
